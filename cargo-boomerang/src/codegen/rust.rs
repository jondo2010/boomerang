fn render_indices(
    source: &mut String,
    name: &str,
    ty: &str,
    values: impl Iterator<Item = u32>,
) -> Result<()> {
    let values = values.collect::<Vec<_>>();
    writeln!(source, "static {name}: [{ty}; {}] = [", values.len())?;
    for value in values {
        writeln!(source, "    {ty}::new({value}),")?;
    }
    source.push_str("];\n");
    Ok(())
}

fn table_range<T>(value: TableRange<T>) -> String {
    format!("TableRange::new({}, {})", value.start(), value.len())
}

fn identity_range(value: IdentityRange) -> String {
    format!("IdentityRange::new({}, {})", value.start(), value.len())
}

fn optional_index(ty: &str, value: Option<u32>) -> String {
    value.map_or_else(
        || String::from("None"),
        |value| format!("Some({ty}::new({value}))"),
    )
}

fn optional_bank(value: Option<BankInfoImage>) -> String {
    value.map_or_else(
        || String::from("None"),
        |value| {
            format!(
                "Some(BankInfoImage::new({}, {}))",
                value.index(),
                value.total()
            )
        },
    )
}

fn action_timing(value: ActionTiming) -> String {
    match value {
        ActionTiming::Standard { domain, min_delay_nanos } => format!("ActionTiming::Standard {{ domain: TimingDomain::{}, min_delay_nanos: {min_delay_nanos} }}", timing_domain(domain)),
        ActionTiming::Timer { period_nanos } => format!("ActionTiming::Timer {{ period_nanos: {period_nanos:?} }}"),
        ActionTiming::Shutdown => String::from("ActionTiming::Shutdown"),
    }
}

fn storage_bounds(value: StorageBounds) -> String {
    format!(
        "StorageBounds::new({}, {}, {}, {}, {}, {})",
        value.state_slots(),
        value.action_slots(),
        value.event_capacity(),
        value.payload_bytes(),
        value.state_bytes(),
        value.scratch_bytes()
    )
}

const fn timing_domain(value: TimingDomain) -> &'static str {
    match value {
        TimingDomain::Logical => "Logical",
        TimingDomain::Physical => "Physical",
    }
}

const fn route_direction(value: RouteDirection) -> &'static str {
    match value {
        RouteDirection::Inbound => "Inbound",
        RouteDirection::Outbound => "Outbound",
    }
}

const fn binding_kind(value: BindingKind) -> &'static str {
    match value {
        BindingKind::StateInitializer => "StateInitializer",
        BindingKind::Reaction => "Reaction",
        BindingKind::Port => "Port",
        BindingKind::Action => "Action",
    }
}

const fn transition(value: TransitionKind) -> &'static str {
    match value {
        TransitionKind::Reset => "Reset",
        TransitionKind::History => "History",
    }
}

#[cfg(test)]
mod tests {
    use boomerang_builder::{ReactionSlot, ReactionSlotId, ReactorSlotId};

    use super::reaction_reactor;

    #[test]
    fn nested_reaction_uses_its_exact_descriptor_owner() {
        let root = ReactorSlotId::new("Root").unwrap();
        let child = ReactorSlotId::new("Root/child").unwrap();
        let reaction = ReactionSlotId::new("Root/child/startup").unwrap();
        let slots = [ReactionSlot {
            id: reaction.clone(),
            reactor: child.clone(),
        }];

        assert_eq!(reaction_reactor(&slots, &reaction).unwrap(), &child);
        assert_ne!(reaction_reactor(&slots, &reaction).unwrap(), &root);
    }
}
